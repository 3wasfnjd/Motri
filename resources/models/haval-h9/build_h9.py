def prism(name,poly,axis,lo,hi,material,group=None,bev=0,seg=3):
    def p(a,b,t):
        return (t,a,b) if axis=='X' else ((a,t,b) if axis=='Y' else (a,b,t))
    v=[p(a,b,t) for t in (lo,hi) for a,b in poly];n=len(poly)
    f=[tuple(range(n-1,-1,-1)),tuple(range(n,2*n))]
