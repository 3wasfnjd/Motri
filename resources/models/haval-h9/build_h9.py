def rounded_path(points,steps=5,factor=.16):
    out=[points[0]]
    for i in range(1,len(points)-1):
        a,b,c=map(Vector,(points[i-1],points[i],points[i+1]));u=b+(a-b)*factor;v=b+(c-b)*factor
        for k in range(steps+1):
            t=k/steps;out.append(tuple((1-t)**2*u+2*(1-t)*t*b+t*t*v))
    out.append(points[-1]);return out

